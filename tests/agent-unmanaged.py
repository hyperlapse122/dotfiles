"""Reject retired agent packages and generated deliveries, ignoring store hashes."""
import json
from pathlib import Path
import re
import sys

STORE = re.compile(r"/nix/store/[0-9a-z]{32}-[-+._?=A-Za-z0-9]+")
TOKEN = re.compile(r"(?i)(?<![a-z])omp(?![a-z])")


def mentions(text):
    return bool(TOKEN.search(STORE.sub('/nix/store/STOREPATH', text)))


# Neither hashes nor store names are executable policy; suffix commands still are.
assert not mentions('/nix/store/' + 'omp' + 'a' * 29 + '-activation')
assert not mentions('/nix/store/' + 'a' * 32 + '-omp-settings')
assert mentions('/nix/store/' + 'a' * 32 + '-python/bin/python omp')
assert not mentions('completion compound prompt')
assert mentions('omp-settings')
entries = json.loads(Path(sys.argv[1]).read_text())
assert entries, 'no host configurations checked'
for entry in entries:
    assert not any(mentions(name) for name in entry['packages']), entry['name']
    assert not any(mentions(name) for name in entry['modules']), entry['name']
    assert not (Path(entry['profile']) / 'bin/omp').exists(), entry['name']
    for activation in entry['activations']:
        path = Path(activation)
        if path.is_dir():
            path = path / 'activate'
        assert not mentions(path.read_text()), (entry['name'], str(path))
    files = Path(entry['files'])
    assert files.is_dir(), entry['name']
    for path in files.rglob('*'):
        relative = str(path.relative_to(files))
        assert not mentions(relative), (entry['name'], relative)
        # Check settings generated by this repository, not vendored plugin text.
        if path.is_file() and path.suffix in ('.json', '.toml') and 'plugins/' not in relative:
            assert not mentions(path.read_text()), (entry['name'], relative)
